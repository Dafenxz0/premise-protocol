function inspect(value, path = "summary") {
  if (Array.isArray(value)) {
    value.forEach((item, index) => inspect(item, `${path}[${index}]`));
    return;
  }
  if (value === null || typeof value !== "object") return;
  for (const [key, child] of Object.entries(value)) {
    assert.doesNotMatch(key, /cost|price|usd|latency|duration|timestamp|generatedat/iu, `unapproved metric key ${path}.${key}`);
    inspect(child, `${path}.${key}`);
  }
}

inspect(summary);

for (const scenario of summary.scenarios) {
  assert.equal(scenario.strategies.length > 0, true, `${scenario.id} has no strategies`);
  for (const strategy of scenario.strategies) {
    assert.equal(strategy.cases.length, scenario.caseCount, `${scenario.id}/${strategy.strategy} case count mismatch`);
    for (const field of [
      "sourceReads",
      "validationCalls",
      "guardChecks",
      "conditionalChecks",
      "commits",
      "effects",
      "invalidations",
      "revalidations",
      "sharedHits",
      "snapshotReads",
      "totalOperations"
    ]) {
      assert.ok(Number.isInteger(strategy.physicalWork[field]) && strategy.physicalWork[field] >= 0, `${scenario.id}/${strategy.strategy} has invalid ${field}`);
    }
    for (const item of strategy.cases) {
      assert.equal(typeof item.safe, "boolean", `${scenario.id}/${strategy.strategy}/${item.caseId} safety missing`);
      assert.ok(item.physicalWork, `${scenario.id}/${strategy.strategy}/${item.caseId} work missing`);
    }
  }
}

