function row(scenarioId, strategyName) {
  const scenario = summary.scenarios.find((item) => item.id === scenarioId);
  assert.ok(scenario, `missing scenario ${scenarioId}`);
  const strategy = scenario.strategies.find((item) => item.strategy === strategyName);
  assert.ok(strategy, `missing strategy ${scenarioId}/${strategyName}`);
  return strategy;
}

