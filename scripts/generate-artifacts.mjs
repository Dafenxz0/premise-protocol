import assert from "node:assert/strict";
import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { GenericMemoryAdapter } from "../examples/generic-memory/dist/index.js";
import { executeTestVectors, runConformance, validateTestVectors } from "../packages/conformance/dist/index.js";
import { runBenchmarkCli } from "../benchmarks/premise-memory-bench/dist/cli.js";

const root = fileURLToPath(new URL("..", import.meta.url));
const at = "2026-08-09T19:20:00Z";
const envelope = {
  specVersion: "premise/0.1",
  memoryId: "memory:artifact",
  provenance: [{ sourceUri: "artifact://fact", observedAt: at, version: { scheme: "artifact", token: "v1" }, validator: { id: "artifact", operation: "read" } }],
  validity: { status: "FRESH", checkedAt: at, policy: "VERSIONED" },
  dependsOn: []
};

const vectorDirectory = join(root, "spec", "test-vectors");
const manifest = JSON.parse(await readFile(join(vectorDirectory, "manifest.json"), "utf8"));
const suites = Object.fromEntries(await Promise.all(manifest.files.map(async (entry) => [
  entry.path,
  JSON.parse(await readFile(join(vectorDirectory, entry.path), "utf8"))
])));
const vectorValidation = validateTestVectors(manifest, suites);
assert.equal(vectorValidation.valid, true, vectorValidation.errors.join("; "));
const vectorExecution = executeTestVectors(manifest, suites);
assert.equal(vectorExecution.valid, true, vectorExecution.failures.join("; "));

const adapter = new GenericMemoryAdapter();
const conformanceAdapter = {
  capabilities: adapter.capabilities,
  register: (record) => adapter.register(record),
  derive: (record) => adapter.derive(record),
  signal: (event) => adapter.signal(event),
  validate: (memoryIds) => adapter.validate(memoryIds),
  check: (memoryIds) => adapter.check(memoryIds),
  history: (memoryId) => adapter.history(memoryId)
};
const conformance = await runConformance(conformanceAdapter, [{
  id: "artifact-contract",
  steps: [
    { id: "register", operation: "register", input: { memoryId: envelope.memoryId, content: { artifact: true }, envelope } },
    { id: "check", operation: "check", input: [envelope.memoryId], expect: [{ memoryId: envelope.memoryId, decision: "USABLE" }] },
    { id: "history", operation: "history", input: envelope.memoryId, expect: [{ type: "MemoryRegistered" }] }
  ]
}]);
assert.equal(conformance.passed, true, JSON.stringify(conformance));
await writeFile(join(root, "conformance-report.json"), `${JSON.stringify({
  format: "premise-conformance-report/0.1",
  passed: vectorValidation.valid && conformance.passed,
  vectorValidation,
  vectorExecution,
  adapterContract: conformance
}, null, 2)}\n`);

const benchmarkRun = await runBenchmarkCli();
const traceDirectory = join(root, "traces");
await mkdir(traceDirectory, { recursive: true });
for (const file of await readdir(traceDirectory)) if (file.endsWith(".json")) await unlink(join(traceDirectory, file));
for (const trace of benchmarkRun.traces) await writeFile(join(traceDirectory, `${trace.episodeId}.json`), `${JSON.stringify(trace, null, 2)}\n`);
const { traces: _traces, ...benchmarkReport } = benchmarkRun;
await writeFile(join(root, "results.json"), `${JSON.stringify(benchmarkReport, null, 2)}\n`);

const successful = benchmarkRun.results.filter((result) => result.taskSuccessRate === 1).map((result) => result.baseline);
const summary = [
  "# PREMiSE v0.1.0-rc.1 verification",
  "",
  "Generated by `pnpm artifacts:generate` on the deterministic v0.1 scenario suite.",
  "",
  `- Conformance vectors: ${vectorExecution.passedCount}/${vectorExecution.vectorCount} executed and passed across ${vectorValidation.suiteCount} suites.`,
  `- Adapter contract: ${conformance.passed ? "PASS" : "FAIL"}.`,
  `- Benchmark: ${benchmarkRun.scenarioCount} scenarios, ${benchmarkRun.controlCount} controls, ${benchmarkRun.ablationCount} ablations, ${benchmarkRun.traceCount} traces.`,
  `- Policies with 100% task success in the scenario run: ${successful.length > 0 ? successful.join(", ") : "none; repairable scenarios score 95% because delete/missing cases remain blocked"}.`,
  "- Generated artifacts: `conformance-report.json`, `results.json`, and `traces/`.",
  "",
  "## Verification commands",
  "",
  "```text",
  "pnpm install --frozen-lockfile",
  "pnpm build",
  "pnpm test",
  "pnpm test:properties",
  "pnpm conformance",
  "pnpm benchmark:smoke",
  "pnpm benchmark -- --runner minimal --suite v0.1",
  "pnpm examples:verify",
  "pnpm artifacts:generate",
  "```",
  ""
].join("\n");
await writeFile(join(root, "summary.md"), summary);
console.log(JSON.stringify({ conformance: conformance.passed && vectorExecution.valid, vectors: vectorExecution.passedCount, benchmark: benchmarkRun.results.length, traces: benchmarkRun.traceCount }));
